from __future__ import annotations

from .conceptual_model import (
    argument_modules,
    claim_dependencies,
    conceptual_integrity_token,
    figure_specs,
    formal_claims,
    quadrant_grid,
    symbol_glossary,
    termination_catalog,
    text_validation_checks,
    used_symbol_keys,
    validate_claim_dependencies,
    validate_conceptual_contract,
)


def build_api_reference_markdown() -> str:
    """Generate a full API reference from the conceptual inventory."""
    lines: list[str] = [
        "# Prior Cognitive Art — Source Reference",
        "",
        "## Conceptual Inventory",
        "",
        f"- Tinbergen quadrants: {len(quadrant_grid())}",
        f"- Termination modes: {len(termination_catalog())}",
        f"- Argument modules: {len(argument_modules())}",
        f"- Generated figures: {len(figure_specs())}",
        f"- Formal claims: {len(formal_claims())}",
        f"- Symbol glossary rows: {len(symbol_glossary())}",
        f"- Text-validation checks: {len(text_validation_checks())}",
        f"- Claim dependencies: {len(claim_dependencies())}",
        f"- Used symbol keys (union): {len(used_symbol_keys())}",
        f"- Integrity token: `{conceptual_integrity_token()}`",
        f"- Contract errors: {list(validate_conceptual_contract()) or 'none'}",
        f"- Dependency errors: {list(validate_claim_dependencies()) or 'none'}",
        "",
        "The source layer stores static concept records and deterministic",
        "visualization wiring. All public symbols are available via",
        "`from src import ...` or the module paths below.",
        "",
        "## Modules",
        "",
        "### `src.conceptual_model`",
        "",
        "Dataclasses for concept records and integrity helpers:",
        "",
        "- `Quadrant` — Tinbergen quadrant with scale, temporality, label,",
        "  role, and regress status.",
        "- `Termination` — Regress termination move with stop type, answer,",
        "  and limitation.",
        "- `ArgumentModule` — Titled argument claim with a key.",
        "- `FigureSpec` — Figure manifest entry with filename, title, purpose, and caption.",
        "- `FormalClaim` — Auto-numbered formal claim with LaTeX expression",
        "  and symbol keys.",
        "- `SymbolSpec` — Glossary row mapping a symbol key to its notation,",
        "  name, and role.",
        "- `TextValidationCheck` — Manuscript-integrity check with surface,",
        "  invariant, and evidence.",
        "",
        "Factory functions returning immutable tuples:",
        "",
        "- `quadrant_grid()` — 4 Tinbergen quadrants.",
        "- `termination_catalog()` — 3 termination moves.",
        "- `argument_modules()` — 10 argument modules.",
        "- `figure_specs()` — 18 figure specifications.",
        "- `formal_claims()` — 11 formal claims.",
        "- `symbol_glossary()` — 25 symbol glossary rows.",
        "- `text_validation_checks()` — 10 text-integrity checks.",
        "",
        "Validation helpers:",
        "",
        "- `validate_conceptual_contract()` — returns a tuple of error",
        "  strings (empty when the contract is closed).",
        "- `used_symbol_keys()` — frozenset of all symbol keys used by",
        "  formal claims.",
        "- `conceptual_integrity_token()` — 16-character SHA-256 prefix",
        "  binding the full conceptual inventory.",
        "- `as_records(items)` — dataclass-to-dict conversion for JSON output.",
        "",
        "### `src.analysis.workflow`",
        "",
        "- `build_conceptual_report(project_root)` — returns a JSON-serializable",
        "  dict with all conceptual records and counts.",
        "- `run_analysis_pipeline(project_root)` — generates figures, reports,",
        "  manifests, and registries under `output/`.",
        "",
        "### `src.figures.conceptual`",
        "",
        "- `generate_all_figures(output_dir)` — public orchestrator that renders",
        "  all 18 conceptual figures as PNG + SVG and validates the manifest.",
        "- Figure drawing functions live in responsibility-split",
        "  `src.figures._*_figures` modules, each kept below the pure-LOC ceiling.",
        "",
        "### `src.manuscript_variables`",
        "",
        "- `generate_variables(project_root, require_analysis_outputs=)` —",
        "  builds the token dictionary for manuscript hydration.",
        "- `save_variables(variables, out_path)` — writes sorted JSON.",
        "",
        "### `src.project_paths`",
        "",
        "- `resolve_project_root(package_name)` — resolves the project root.",
        "- `project_output_dirs(project_root)` — returns a dict of output paths.",
        "",
        "### `src._runtime`",
        "",
        "- `get_logger(module_name)` — infrastructure-aware logger.",
        "- `project_root(caller)` — convenience path resolver.",
        "",
        "## Figure Inventory",
        "",
        "| Key | Filename | Purpose |",
        "|---|---|---|",
    ]
    for spec in figure_specs():
        lines.append(f"| `{spec.key}` | `{spec.filename}` | {spec.caption} |")

    lines.extend([
        "",
        "## Formal Claims",
        "",
    ])
    for i, claim in enumerate(formal_claims(), start=1):
        lines.append(f"### F{i}: {claim.title}")
        lines.append("")
        lines.append(f"- Expression: `{claim.expression}`")
        lines.append(f"- Symbols: {', '.join(claim.symbol_keys)}")
        lines.append(f"- Reading: {claim.reading}")
        lines.append("")

    return "\n".join(lines) + "\n"
